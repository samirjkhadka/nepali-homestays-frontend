/**
 * One-off: projects province GeoJSON (Acesmndr/nepal-geojson) to viewBox 900x500,
 * decimates vertices, emits TypeScript for InteractiveProvinceMap.
 * Run: node scripts/build-nepal-map-data.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const GEO_DIR = path.join(__dirname, 'tmp-nepal-geo');
const OUT = path.join(__dirname, '../src/data/nepalProvinceMapPaths.ts');

const W = 900;
const H = 500;
const PAD = 28;
const STEP = 4; // keep every STEPth vertex to limit file size

/** GeoJSON province number 1..7 -> app province id (same numbering) */
const FILES = [
  { file: 'Province-1.geojson', id: 1 },
  { file: 'Province-2.geojson', id: 2 },
  { file: 'Province-3.geojson', id: 3 },
  { file: 'Province-4.geojson', id: 4 },
  { file: 'Province-5.geojson', id: 5 },
  { file: 'Province-6.geojson', id: 6 },
  { file: 'Province-7.geojson', id: 7 },
];

function getOuterRing(geometry) {
  if (geometry.type === 'Polygon') return geometry.coordinates[0];
  if (geometry.type === 'MultiPolygon') {
    let best = null;
    let bestA = 0;
    for (const poly of geometry.coordinates) {
      const ring = poly[0];
      let a = 0;
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        a += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
      }
      a = Math.abs(a / 2);
      if (a > bestA) {
        bestA = a;
        best = ring;
      }
    }
    return best;
  }
  throw new Error('unsupported geometry');
}

function decimate(ring) {
  const out = [];
  for (let i = 0; i < ring.length; i += STEP) out.push(ring[i]);
  if (out[out.length - 1] !== ring[ring.length - 1]) out.push(ring[ring.length - 1]);
  return out;
}

const allRings = [];
for (const { file } of FILES) {
  const p = path.join(GEO_DIR, file);
  const feature = JSON.parse(fs.readFileSync(p, 'utf8'));
  const ring = getOuterRing(feature.geometry);
  allRings.push(decimate(ring));
}

let minLon = Infinity,
  maxLon = -Infinity,
  minLat = Infinity,
  maxLat = -Infinity;
for (const ring of allRings) {
  for (const [lon, lat] of ring) {
    minLon = Math.min(minLon, lon);
    maxLon = Math.max(maxLon, lon);
    minLat = Math.min(minLat, lat);
    maxLat = Math.max(maxLat, lat);
  }
}

const innerW = W - 2 * PAD;
const innerH = H - 2 * PAD;
const scale = Math.min(innerW / (maxLon - minLon), innerH / (maxLat - minLat));
const offX = PAD + (innerW - (maxLon - minLon) * scale) / 2;
const offY = PAD + (innerH - (maxLat - minLat) * scale) / 2;

function project([lon, lat]) {
  const x = offX + (lon - minLon) * scale;
  const y = offY + (maxLat - lat) * scale;
  return [x, y];
}

function ringToPath(ring) {
  const pts = ring.map(project);
  const d = pts
    .map((p, i) => `${i === 0 ? 'M' : 'L'} ${p[0].toFixed(1)} ${p[1].toFixed(1)}`)
    .join(' ');
  return `${d} Z`;
}

function centroid(ring) {
  const pts = ring.map(project);
  let cx = 0,
    cy = 0;
  for (const [x, y] of pts) {
    cx += x;
    cy += y;
  }
  return { cx: cx / pts.length, cy: cy / pts.length };
}

const lines = [];
lines.push(`/**`);
lines.push(` * Auto-generated by scripts/build-nepal-map-data.mjs from`);
lines.push(` * https://github.com/Acesmndr/nepal-geojson (Province-1..7.geojson, MIT).`);
lines.push(` * Simplified for SVG; not survey-grade.`);
lines.push(` */`);
lines.push(``);
lines.push(`export type NepalMapPathEntry = { id: number; path: string; cx: number; cy: number };`);
lines.push(``);
lines.push(`export const NEPAL_MAP_PROJECTION = {`);
lines.push(`  viewBox: '0 0 ${W} ${H}',`);
lines.push(`  width: ${W},`);
lines.push(`  height: ${H},`);
lines.push(`} as const;`);
lines.push(``);
lines.push(`export const NEPAL_PROVINCE_PATHS: NepalMapPathEntry[] = [`);

for (let i = 0; i < FILES.length; i++) {
  const { id } = FILES[i];
  const pathStr = ringToPath(allRings[i]);
  const c = centroid(allRings[i]);
  lines.push(
    `  { id: ${id}, path: ${JSON.stringify(pathStr)}, cx: ${c.cx.toFixed(1)}, cy: ${c.cy.toFixed(1)} },`,
  );
}

lines.push(`];`);
lines.push(``);

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log('Wrote', OUT);
